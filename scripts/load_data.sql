-- Migrate the original one-row-per-filename audit table without discarding its history.
alter table raw.load_audit
    add column if not exists load_id bigint generated by default as identity;
alter table raw.load_audit
    add column if not exists source_file_size_bytes bigint;

do $$
declare
    primary_key_name text;
    primary_key_columns text[];
begin
    select
        constraint_row.conname,
        array(
            select attribute_row.attname::text
            from unnest(constraint_row.conkey) with ordinality as key_column(attnum, ordinal)
            join pg_attribute as attribute_row
              on attribute_row.attrelid = constraint_row.conrelid
             and attribute_row.attnum = key_column.attnum
            order by key_column.ordinal
        )
    into primary_key_name, primary_key_columns
    from pg_constraint as constraint_row
    where constraint_row.conrelid = 'raw.load_audit'::regclass
      and constraint_row.contype = 'p';

    if primary_key_name is not null
       and primary_key_columns is distinct from array['load_id']::text[] then
        execute format('alter table raw.load_audit drop constraint %I', primary_key_name);
        primary_key_name := null;
    end if;

    if primary_key_name is null then
        alter table raw.load_audit
            add constraint load_audit_pkey primary key (load_id);
    end if;
end $$;

